/**
 * extractMetadata.js
 *
 * Source section: document-wide.
 *   - Product name: the repeating page header "Quotation for <Name>" /
 *     "<Product Name>" (see lineUtils.findRepeatingHeader).
 *   - quotationDate / quotationVersion / symcode: the repeating page
 *     footer ("Date : ...", "Version : ...", "SYMCODE : ..."), which is
 *     printed identically on every content page - we take the first
 *     occurrence anywhere in the document.
 *   - pageCount: the "Page X of Y" footer line.
 *
 * Extraction method: anchor-label. Regex is used only to clean values
 * (date format, trailing page-count number).
 *
 * Expected output:
 *   { productName, quotationDate, quotationVersion, symcode, pageCount,
 *     sourceFileName, quotationNumber, validUntil, _warnings }
 *
 * IMPORTANT - fields NOT sourced from the PDF:
 *   quotationNumber and validUntil do not exist anywhere in PruBSN's
 *   document. They are GENERATED by this tool (see below) and must be
 *   surfaced to the agent as editable/assigned values, never presented as
 *   facts read from the source document. (A previous hand-made version of
 *   this quotation fabricated a "Quotation No" that looked authoritative
 *   but wasn't - this is the fix for that.)
 */

'use strict';

const {
  findAnchorIndexInDoc,
  getValueAfterColon,
  findRepeatingHeader,
  parseDateDMY,
} = require('./lineUtils');

function addDaysIso(iso, days) {
  const d = new Date(iso + 'T00:00:00Z');
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}

function extractMetadata(doc, options = {}) {
  const warnings = [];
  const {
    sourceFileName = null,
    validityDays = 14,
    quotationNumber = null,
  } = options;

  const header = findRepeatingHeader(doc);
  const productName = header ? header.productName : null;
  if (!productName) {
    warnings.push({
      field: 'metadata.productName',
      message: 'Could not locate the repeating page header "Quotation for ...".',
    });
  }

  const dateIdx = findAnchorIndexInDoc(doc, /^Date\s*:/i);
  let quotationDate = null;
  if (dateIdx !== -1) {
    const raw = getValueAfterColon(doc.allLines[dateIdx].text, 'Date');
    quotationDate = raw ? parseDateDMY(raw) : null;
  }
  if (!quotationDate) {
    warnings.push({
      field: 'metadata.quotationDate',
      message: 'Could not locate "Date :" in the page footer.',
    });
  }

  const versionIdx = findAnchorIndexInDoc(doc, /^Version\s*:/i);
  const quotationVersion =
    versionIdx !== -1
      ? getValueAfterColon(doc.allLines[versionIdx].text, 'Version')
      : null;

  const symcodeIdx = findAnchorIndexInDoc(doc, /SYMCODE\s*:/i);
  const symcode =
    symcodeIdx !== -1
      ? getValueAfterColon(doc.allLines[symcodeIdx].text, 'SYMCODE')
      : null;

  const pageCountLine = doc.allLines.find((l) => /Page\s+\d+\s+of\s+\d+/i.test(l.text));
  const pageCountMatch = pageCountLine
    ? pageCountLine.text.match(/Page\s+\d+\s+of\s+(\d+)/i)
    : null;
  const pageCount = pageCountMatch ? parseInt(pageCountMatch[1], 10) : doc.pageCount;
  if (!pageCountMatch) {
    warnings.push({
      field: 'metadata.pageCount',
      message: 'Could not locate a "Page X of Y" footer line; falling back to page array length.',
    });
  }

  // --- Generated fields (NOT extracted - see file header) ---
  const validUntilIso = quotationDate ? addDaysIso(quotationDate.iso, validityDays) : null;

  return {
    productName,
    quotationDate,
    quotationVersion,
    symcode,
    pageCount,
    sourceFileName,
    quotationNumber: {
      value: quotationNumber,
      generated: true,
      note: 'Not present in source PDF - assign or edit before sending to client.',
    },
    validUntil: validUntilIso
      ? {
          iso: validUntilIso,
          generated: true,
          basis: `quotationDate + ${validityDays} days`,
        }
      : null,
    _warnings: warnings,
  };
}

module.exports = { extractMetadata };
